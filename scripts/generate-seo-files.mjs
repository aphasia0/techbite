#!/usr/bin/env node
/**
 * Generates build-time SEO files from the Supabase blog_pages table:
 *
 *   dist/myapp/sitemap.xml  — XML sitemap with lastmod
 *   dist/myapp/_redirects   — explicit routes + real 404 fallback (Netlify)
 *   dist/myapp/404.html     — static 404 page with noindex
 *
 * Runs after `ng build` (see package.json). The Supabase URL and publishable
 * key are read from src/environments/environment.prod.ts, like seed-blog.mjs.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const distDir = path.join(root, 'dist', 'myapp');
const envFile = path.join(root, 'src', 'environments', 'environment.prod.ts');
const siteUrl = 'https://antoniogiordano.dev';

const staticRoutes = ['/home', '/stories', '/my-projects', '/about', '/pdf-remove-password'];

function readEnvironment() {
  if (!fs.existsSync(envFile)) {
    throw new Error(`Environment file not found: ${envFile}`);
  }

  const source = fs.readFileSync(envFile, 'utf8');

  return {
    url: source.match(/supabaseUrl:\s*'([^']+)'/)?.[1],
    anonKey: source.match(/supabaseAnonKey:\s*'([^']+)'/)?.[1],
  };
}

async function fetchPosts(url, key) {
  const endpoint = `${url}/rest/v1/blog_pages?select=id,published_at&order=published_at.desc`;
  const response = await fetch(endpoint, {
    headers: {
      apikey: key,
      Authorization: `Bearer ${key}`,
    },
  });

  if (!response.ok) {
    throw new Error(`Supabase request failed (${response.status}): ${await response.text()}`);
  }

  const rows = await response.json();

  return rows.filter(
    (row) => typeof row.id === 'string' && /^[a-z0-9-]+$/.test(row.id)
  );
}

function escapeXml(value) {
  return String(value).replace(
    /[<>&'"]/g,
    (char) =>
      ({ '<': '&lt;', '>': '&gt;', '&': '&amp;', "'": '&apos;', '"': '&quot;' })[char]
  );
}

function buildSitemap(posts) {
  const entries = staticRoutes.map((route) => ({ loc: `${siteUrl}${route}` }));

  for (const post of posts) {
    entries.push({
      loc: `${siteUrl}/blog/${post.id}`,
      lastmod: typeof post.published_at === 'string' ? post.published_at.slice(0, 10) : undefined,
    });
  }

  const urls = entries
    .map(({ loc, lastmod }) => {
      const lastmodTag = lastmod ? `\n    <lastmod>${escapeXml(lastmod)}</lastmod>` : '';
      return `  <url>\n    <loc>${escapeXml(loc)}</loc>${lastmodTag}\n  </url>`;
    })
    .join('\n');

  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`;
}

function buildRedirects(posts) {
  // Netlify normalises trailing slashes when matching rules: a rule "/home/ -> /home 301"
  // also matches "/home" and produces an infinite redirect. Keep both variants as rewrites.
  const lines = [
    '# Generated by scripts/generate-seo-files.mjs',
    '/            /home           301!',
    '/index.html  /home           301!',
  ];

  for (const route of staticRoutes) {
    lines.push(`${route}  /index.html  200`);
    lines.push(`${route}/  /index.html  200`);
  }

  for (const post of posts) {
    lines.push(`/blog/${post.id}  /index.html  200`);
    lines.push(`/blog/${post.id}/  /index.html  200`);
  }

  lines.push('/blog/*  /index.html  200');
  lines.push('/*       /404.html  404');

  return `${lines.join('\n')}\n`;
}

function buildNotFoundPage() {
  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <title>Page not found — Techbite</title>
  <meta name="robots" content="noindex,follow">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <style>
    :root { color-scheme: light; }
    body { display: grid; min-height: 100vh; margin: 0; place-items: center; background: #fff; color: #222; font-family: Inter, -apple-system, system-ui, Roboto, sans-serif; }
    main { width: min(100% - 48px, 560px); padding: 48px 0; text-align: center; }
    .eyebrow { margin: 0 0 12px; color: #ff385c; font-size: 13px; font-weight: 700; letter-spacing: 0.16em; text-transform: uppercase; }
    h1 { margin: 0 0 12px; font-size: 28px; line-height: 1.3; }
    p { margin: 0 0 24px; color: #3f3f3f; }
    a { display: inline-block; padding: 14px 24px; border-radius: 8px; background: #ff385c; color: #fff; font-weight: 500; text-decoration: none; }
    a:hover { background: #e00b41; }
  </style>
</head>
<body>
  <main>
    <p class="eyebrow">404</p>
    <h1>This page does not exist</h1>
    <p>The link may be broken or the story may have moved. Every published note is still on the stories page.</p>
    <a href="/home">Browse all stories</a>
  </main>
</body>
</html>
`;
}

async function main() {
  if (!fs.existsSync(distDir)) {
    throw new Error(`Build output not found at ${distDir}. Run "ng build" before this script.`);
  }

  const { url, anonKey } = readEnvironment();

  if (!url || !anonKey) {
    throw new Error('Unable to read supabaseUrl/supabaseAnonKey from environment.prod.ts');
  }

  const posts = await fetchPosts(url, anonKey);

  if (posts.length === 0) {
    throw new Error('No blog posts returned by Supabase: refusing to write an empty sitemap.');
  }

  fs.writeFileSync(path.join(distDir, 'sitemap.xml'), buildSitemap(posts));
  fs.writeFileSync(path.join(distDir, '_redirects'), buildRedirects(posts));
  fs.writeFileSync(path.join(distDir, '404.html'), buildNotFoundPage());

  const legacySitemap = path.join(distDir, 'sitemap.txt');
  if (fs.existsSync(legacySitemap)) {
    fs.rmSync(legacySitemap);
  }

  console.log(
    `SEO files written: sitemap.xml (${posts.length} posts + ${staticRoutes.length} pages), _redirects, 404.html`
  );
}

main().catch((error) => {
  console.error(error.message ?? error);
  process.exit(1);
});
